"""Pack ball-art/*.png into ball_assets.h: one 16x16 four-bit texture and one
16-colour BGR555 palette per ball, in White 2 ball ID order (1-25)."""
import argparse
from pathlib import Path
from PIL import Image
HERE=Path(__file__).resolve().parent
# pml_item.c MONS_BALL_ITEMS: ball ID n is BALLS[n-1].
BALLS=('master','ultra','great','poke','safari','net','dive','nest','repeat','timer','luxury','premier',
       'dusk','heal','quick','cherish','fast','level','lure','heavy','love','friend','moon','sport','dream')
p=argparse.ArgumentParser(description=__doc__);p.add_argument('--art',type=Path,default=HERE/'ball-art');args=p.parse_args()
textures=[];palettes=[]
for name in BALLS:
    path=args.art/f'{name}.png'
    image=Image.open(path)
    if image.size!=(16,16) or image.mode!='P' or image.info.get('transparency')!=0:
        raise ValueError(f'{path.name}: expected a 16x16 indexed PNG with index 0 transparent')
    pixels=list(image.get_flattened_data() if hasattr(image,'get_flattened_data') else image.getdata())
    if max(pixels)>15:raise ValueError(f'{path.name}: uses palette index {max(pixels)}; at most 15')
    if any(pixels[:5*16]) or any(pixels[15*16:]):raise ValueError(f'{path.name}: art must stay in rows 5-14')
    textures.append(bytes(pixels[i]|pixels[i+1]<<4 for i in range(0,256,2)))
    rgb=image.getpalette()+[0]*48
    palettes.append([0]+[rgb[i*3]>>3|(rgb[i*3+1]>>3)<<5|(rgb[i*3+2]>>3)<<10 for i in range(1,16)])
out=['/* Generated by import_balls.py from ball-art/; White 2 ball IDs 1-25. */',
     f'#define FW_BALL_COUNT {len(BALLS)}u','static const uint8_t fw_ball_tex[FW_BALL_COUNT][128] = {']
for name,tex in zip(BALLS,textures):
    out.append(f'    /* {name} */ {{'+', '.join(str(b) for b in tex)+'},')
out+=['};','static const uint16_t fw_ball_pltt[FW_BALL_COUNT][16] = {']
for name,pal in zip(BALLS,palettes):
    out.append(f'    /* {name} */ {{'+', '.join(f'0x{c:04x}' for c in pal)+'},')
out.append('};')
(HERE/'ball_assets.h').write_text('\n'.join(out)+'\n')
print(f'Packed {len(BALLS)} balls into ball_assets.h.')
